
-- Reconcile the notifications table with the migration history
-- and support notifications that are not related to posts.

CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL,
    actor_user_id BIGINT,
    notification_type VARCHAR(30) NOT NULL,
    post_id BIGINT,
    comment_id BIGINT,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT notifications_no_self_notification
        CHECK (
            actor_user_id IS NULL
            OR actor_user_id <> recipient_user_id
        ),

    CONSTRAINT notifications_notification_type_check
        CHECK (
            notification_type IN (
                'post_like',
                'post_comment',
                'comment_reply',
                'user_follow',
                'follow_request',
                'follow_request_accepted'
            )
        ),

    CONSTRAINT notifications_recipient_user_id_fkey
        FOREIGN KEY (recipient_user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE,

    CONSTRAINT notifications_actor_user_id_fkey
        FOREIGN KEY (actor_user_id)
        REFERENCES public.users(id)
        ON DELETE SET NULL,

    CONSTRAINT notifications_post_id_fkey
        FOREIGN KEY (post_id)
        REFERENCES public.posts(id)
        ON DELETE CASCADE,

    CONSTRAINT notifications_comment_id_fkey
        FOREIGN KEY (comment_id)
        REFERENCES public.comments(id)
        ON DELETE CASCADE
);

-- Follow-related notifications do not reference a post.
ALTER TABLE public.notifications
    ALTER COLUMN post_id DROP NOT NULL;

-- Expand the supported notification types without deleting existing records.
ALTER TABLE public.notifications
    DROP CONSTRAINT IF EXISTS notifications_notification_type_check;

ALTER TABLE public.notifications
    ADD CONSTRAINT notifications_notification_type_check
    CHECK (
        notification_type IN (
            'post_like',
            'post_comment',
            'comment_reply',
            'user_follow',
            'follow_request',
            'follow_request_accepted'
        )
    );

-- Keep the existing indexes and ensure they exist on fresh databases.
CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created
    ON public.notifications (
        recipient_user_id,
        created_at DESC,
        id DESC
    );

CREATE INDEX IF NOT EXISTS idx_notifications_unread
    ON public.notifications (
        recipient_user_id,
        created_at DESC
    )
    WHERE read_at IS NULL;
